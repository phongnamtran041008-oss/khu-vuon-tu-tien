#!/usr/bin/env python3
"""Build server/data/creatures/fish.json from tools/curation/fish.json (spec 11.3, 5).

Nothing linguistic is typed by hand for real fish: the Chinese name is looked up in
CC-CEDICT, which gives the pinyin and the English meaning. Legendary fish with invented
names (`fictional: true`) carry a numeric reading per character; every syllable must be a
CC-CEDICT reading of that character. Fish names are never used as vocabulary questions.

    python tools/build_fish.py          # uses tools/raw/cedict.txt (downloads it if missing)
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))
sys.path.insert(0, str(ROOT / "server"))

from app.learning import pinyin as py  # noqa: E402
from build_bees import cedict_date, ensure_cedict  # noqa: E402
from build_wordlist import load_cedict  # noqa: E402

CUR = ROOT / "tools" / "curation" / "fish.json"
OUT = ROOT / "server" / "data" / "creatures" / "fish.json"
BAITS = ROOT / "server" / "data" / "items" / "baits.json"
RARITIES = ["pham", "linh", "huyen", "dia", "thien"]
POOLS = {"ao", "ho"}
SHAPES = {"round", "long", "eel", "squid"}


def main() -> int:
    ensure_cedict()
    ced = load_cedict()
    baits = {k for k in json.loads(BAITS.read_text("utf-8")) if not k.startswith("_")}
    cur = json.loads(CUR.read_text("utf-8"))
    out, errors = {}, []
    for s in cur["species"]:
        sid = s["id"]
        if sid in out:
            errors.append(f"{sid}: duplicate id")
        hanzi = s["hanzi"]
        if s.get("fictional"):
            numeric = s.get("pinyin_numeric", "")
            syl = numeric.split()
            if len(syl) != len(hanzi):
                errors.append(f"{sid}: {len(syl)} syllables for {len(hanzi)} characters")
                continue
            for ch, sy in zip(hanzi, syl):
                readings = {py.canonical(e["pinyin"]) for e in ced.get(ch, [])}
                if py.canonical(sy) not in readings:
                    errors.append(f"{sid}: {sy} is not a CC-CEDICT reading of {ch} ({sorted(readings)})")
            meaning_en = None
        else:
            entries = ced.get(hanzi, [])
            if not entries:
                errors.append(f"{sid}: {hanzi} is not in CC-CEDICT")
                continue
            numeric = py.canonical(entries[0]["pinyin"])
            meaning_en = "; ".join(d for d in entries[0]["defs"] if d)
        if s["rarity"] not in RARITIES:
            errors.append(f"{sid}: bad rarity {s['rarity']}")
        if not s["pools"] or set(s["pools"]) - POOLS:
            errors.append(f"{sid}: bad pools {s['pools']}")
        if s["time"] not in ("any", "day", "night") or s["weather"] not in ("any", "rain", "clear"):
            errors.append(f"{sid}: bad time/weather")
        if s["bait"] is not None and set(s["bait"]) - baits:
            errors.append(f"{sid}: unknown bait {s['bait']}")
        if s["shape"] not in SHAPES:
            errors.append(f"{sid}: bad shape {s['shape']}")
        lo, hi = s["size_cm"]
        if not 0 < lo < hi:
            errors.append(f"{sid}: bad size range")
        out[sid] = {
            "name_vi": s["name_vi"], "hanzi": hanzi,
            "pinyin": py.numeric_to_marked(numeric), "pinyin_numeric": numeric,
            "meaning_en": meaning_en,
            "fictional": bool(s.get("fictional")), "mythical": bool(s.get("mythical")),
            "rarity": s["rarity"], "pools": s["pools"], "time": s["time"], "weather": s["weather"],
            "bait": s["bait"], "tags": s["tags"], "size_cm": s["size_cm"], "sell_price": s["sell_price"],
            "shape": s["shape"], "color": s["color"], "color2": s.get("color2"), "desc_vi": s["desc_vi"],
        }
    for r in RARITIES:
        if not any(v["rarity"] == r for v in out.values()):
            errors.append(f"no species of rarity {r}")
    if len(out) < 30:
        errors.append(f"only {len(out)} species (spec 11.3 asks for at least 30)")
    if errors:
        print("\n".join("  ! " + e for e in errors))
        return 1
    data = {"_comment": "Generated by tools/build_fish.py from tools/curation/fish.json. Do not edit by hand.",
            "_sources": {"cedict": f"CC-CEDICT {cedict_date()}"}, **out}
    OUT.write_bytes((json.dumps(data, ensure_ascii=False, indent=1) + "\n").encode("utf-8"))
    print(f"wrote {OUT.relative_to(ROOT)}: {len(out)} species "
          f"({sum(v['fictional'] for v in out.values())} fictional names)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
